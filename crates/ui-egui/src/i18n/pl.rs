/// Polish — CLDR (whole numbers): one for 1; few for 2–4, 22–24…; many for the
/// rest (0, 5–21, 25–31…).
fn plural(n: u64) -> Plural {
    if n == 1 {
        return Plural::One;
    }
    match (n % 10, n % 100) {
        (2..=4, r) if !(12..=14).contains(&r) => Plural::Few,
        _ => Plural::Many,
    }
}

