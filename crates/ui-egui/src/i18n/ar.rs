/// Arabic — CLDR (whole numbers): zero for 0; one for 1; two for 2; few for
/// 3–10, 103–110…; many for 11–99, 111–199…; other for the rest (100,
/// 101, 102…).
fn plural(n: u64) -> Plural {
    match (n, n % 100) {
        (0, _) => Plural::Zero,
        (1, _) => Plural::One,
        (2, _) => Plural::Two,
        (_, 3..=10) => Plural::Few,
        (_, 11..=99) => Plural::Many,
        _ => Plural::Other,
    }
}

