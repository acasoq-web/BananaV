/// Russian — CLDR (whole numbers): one for 1, 21, 31…; few for 2–4, 22–24…;
/// many for the rest (0, 5–20, 25–30…).
fn plural(n: u64) -> Plural {
    match (n % 10, n % 100) {
        (1, r) if r != 11 => Plural::One,
        (2..=4, r) if !(12..=14).contains(&r) => Plural::Few,
        _ => Plural::Many,
    }
}

