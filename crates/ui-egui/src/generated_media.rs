//! The Video Media Generators window, as VEGAS's: a generated event's
//! generator and its settings' columns; the frame size and the generated
//! media's duration, with the plug-in's help (Titles & Text), Replace
//! Plug-In (another generator in its place), Match Event Length and Media
//! Properties; the preset (saved and deleted here too); and the plug-in's
//! settings (an OFX generator's as it describes them). The event's
//! Generated Media button opens it, and a preset's + in the Media
//! Generator window (which adds the event at the cursor first).

use bv_core::{Tick, timecode};
use bv_timeline::{ClipId, Generator, MediaId, MediaSource, Project};

use crate::app::BananaApp;
use crate::color_picker::{ColorPicker, Outcome};
use crate::egui::{self, RichText};
use crate::i18n::tr;
use crate::icons::Icon;
use crate::settings::GeneratorPreset;
use crate::theme;
use crate::widgets::icon_button_ex;

/// The window, for one event.
#[derive(Debug)]
pub struct GeneratedMediaWindow {
    clip: ClipId,
    /// The generated media's duration, as typed.
    length: String,
    /// The preset's name, as typed (to save it).
    preset: String,
    /// A color being chosen: which (0: the color, or the gradient's first;
    /// 1: its second) and the picker.
    picking: Option<(usize, ColorPicker)>,
    /// The settings' width measured last frame: the bars above take it.
    width: f32,
}

/// The window's least width (VEGAS's).
const LEAST_WIDTH: f32 = 500.0;

/// How long generated media lasts: its own duration when it has one (a
/// `.veg`'s, or one typed here), else its event's.
fn own_length(info: &bv_timeline::MediaInfo, event: Tick) -> Tick {
    if info.duration < Generator::DURATION {
        info.duration
    } else {
        event
    }
}

/// A ▾ opening the presets' list.
pub(crate) fn list_button(ui: &mut egui::Ui) -> egui::Response {
    let (rect, resp) = ui.allocate_exact_size(egui::vec2(16.0, 22.0), egui::Sense::click());
    if resp.hovered() {
        ui.painter().rect_filled(rect, 2.0, theme::hover());
    }
    let c = rect.center();
    ui.painter().add(egui::Shape::convex_polygon(
        vec![
            c + egui::vec2(-4.0, -2.0),
            c + egui::vec2(4.0, -2.0),
            c + egui::vec2(0.0, 3.0),
        ],
        theme::text(),
        egui::Stroke::NONE,
    ));
    resp.widget_info(|| egui::WidgetInfo::labeled(egui::WidgetType::Button, true, tr("Presets")));
    resp.on_hover_text(tr("Presets"))
}

/// Transfer Text Properties, as VEGAS's: the other events of `clip`'s
/// track made by `fx`'s plug-in take `fx`'s settings, each keeping its own
/// values of the parameters `keep` names (Titles & Text's text). Returns
/// how many changed.
pub(crate) fn transfer_text_properties(
    p: &mut Project,
    clip: ClipId,
    fx: &bv_timeline::PluginFx,
    keep: &[String],
) -> usize {
    let Some(track) = p.clip_track(clip) else {
        return 0;
    };
    let own = p.clip(clip).map(|c| c.media);
    let mut medias: Vec<MediaId> = track
        .clips
        .iter()
        .map(|c| c.media)
        .filter(|&m| Some(m) != own)
        .collect();
    medias.sort();
    medias.dedup();
    let mut changed = 0;
    for m in p.media.iter_mut().filter(|m| medias.contains(&m.id)) {
        let MediaSource::Generated(Generator::Plugin(theirs)) = &mut m.source else {
            continue;
        };
        if theirs.id != fx.id {
            continue;
        }
        let mut params = fx.params.clone();
        for name in keep {
            params.remove(name);
            if let Some(own) = theirs.params.get(name) {
                params.insert(name.clone(), own.clone());
            }
        }
        if theirs.params != params {
            theirs.params = params;
            changed += 1;
        }
    }
    changed
}

/// Generator colors are sRGB, 0–1; the picker's are bytes.
fn to_bytes(c: [f32; 4]) -> [u8; 4] {
    c.map(|v| (v.clamp(0.0, 1.0) * 255.0).round() as u8)
}

fn from_bytes(c: [u8; 4]) -> [f32; 4] {
    c.map(|v| v as f32 / 255.0)
}

/// `g` with its color `which` replaced.
fn with_color(g: &Generator, which: usize, rgba: [f32; 4]) -> Generator {
    match (g.clone(), which) {
        (Generator::SolidColor { .. }, _) => Generator::SolidColor { rgba },
        (Generator::Gradient { to, angle_deg, .. }, 0) => Generator::Gradient {
            from: rgba,
            to,
            angle_deg,
        },
        (
            Generator::Gradient {
                from, angle_deg, ..
            },
            _,
        ) => Generator::Gradient {
            from,
            to: rgba,
            angle_deg,
        },
        (other, _) => other,
    }
}

/// Media `id` generated by `g` from now on (its name follows when it was
/// the generator's own).
fn set_generator(p: &mut Project, id: MediaId, g: Generator) {
    if let Some(m) = p.media.iter_mut().find(|m| m.id == id) {
        if let MediaSource::Generated(old) = &m.source
            && m.name == old.display_name()
        {
            m.name = g.display_name();
        }
        m.source = MediaSource::Generated(g);
    }
}

impl BananaApp {
    /// Opens the Video Media Generators window for event `clip` (of
    /// generated media).
    pub(crate) fn open_generated_media(&mut self, clip: ClipId) {
        let p = self.project();
        let Some(c) = p.clip(clip) else {
            return;
        };
        let Some(MediaSource::Generated(g)) = p.media(c.media).map(|m| m.source.clone()) else {
            return;
        };
        let length = p
            .media(c.media)
            .map_or(c.duration, |m| own_length(m, c.duration));
        let length = timecode::format(length, self.frame_rate());
        let (_, _, presets) = crate::tabs::generators::plugin_of(self, &g);
        let preset = presets
            .into_iter()
            .find(|(_, p)| *p == g)
            .map(|(n, _)| n)
            .unwrap_or_default();
        self.generated_media = Some(GeneratedMediaWindow {
            clip,
            length,
            preset,
            picking: None,
            width: LEAST_WIDTH,
        });
    }

    /// The Video Media Generators window of the first gradient on the
    /// timeline, or of the first generated event (for screen tests).
    pub fn generated_media_for_review(&mut self) {
        let p = self.project();
        let generated = |gradient: bool| {
            p.clips()
                .find(|(_, c)| {
                    p.media(c.media).is_some_and(|m| match &m.source {
                        MediaSource::Generated(Generator::Plugin(fx))
                            if fx.id == "org.bananav.ColorGradient" =>
                        {
                            true
                        }
                        MediaSource::Generated(_) => !gradient,
                        MediaSource::File { .. } => false,
                    })
                })
                .map(|(_, c)| c.id)
        };
        if let Some(clip) = generated(true).or_else(|| generated(false)) {
            self.open_generated_media(clip);
        }
    }

    pub(crate) fn generated_media_window(&mut self, ctx: &egui::Context) {
        let Some(mut w) = self.generated_media.take() else {
            return;
        };
        if w.show(ctx, self) {
            self.generated_media = Some(w);
        }
    }
}

impl GeneratedMediaWindow {
    /// Shows the window; whether it stays open.
    fn show(&mut self, ctx: &egui::Context, app: &mut BananaApp) -> bool {
        let p = app.project();
        let Some(clip) = p.clip(self.clip) else {
            return false;
        };
        let (media, duration) = (clip.media, clip.duration);
        let Some(info) = p.media(media).cloned() else {
            return false;
        };
        let MediaSource::Generated(generator) = info.source.clone() else {
            return false;
        };
        let rate = app.frame_rate();
        let (key, plugin, presets) = crate::tabs::generators::plugin_of(app, &generator);
        let place = crate::ofx::generator_place(app.project(), self.clip, app.cursor);
        let video = info.video;
        let title = if video.is_some() {
            tr("Video Media Generators")
        } else {
            tr("Audio Media Generators")
        };
        let mut open = true;
        let mut chosen: Option<Generator> = None;
        let mut size: Option<(u32, u32)> = None;
        let mut length: Option<Tick> = None;
        let mut save = false;
        let mut delete = false;
        let mut properties = false;
        let mut replacing: Option<Generator> = None;
        let replacements = crate::tabs::generators::replacements(app, video.is_some());
        let user_preset = app
            .settings
            .generator_presets
            .iter()
            .any(|s| s.plugin == key && s.name == self.preset.trim());
        // Titles & Text has the plug-in's help, as VEGAS's.
        let help = match &generator {
            Generator::Plugin(fx) if fx.id == bv_engine::plugins::TITLES_ID => {
                crate::ofx::generators()
                    .into_iter()
                    .find(|p| p.identifier == fx.id)
            }
            _ => None,
        };
        let is_plugin = matches!(generator, Generator::Plugin(_));
        let mut match_length = false;
        let mut measured: Option<f32> = None;
        crate::floating::Window::new(title)
            .id(egui::Id::new("generated-media-window"))
            .collapsible(false)
            .resizable(false)
            .open(&mut open)
            .show(ctx, |ui| {
                let width = self.width.max(LEAST_WIDTH);
                ui.set_width(width);
                // Which generator, and its settings' columns on the right.
                ui.horizontal(|ui| {
                    let which = if video.is_some() {
                        tr("Video Media Generator:")
                    } else {
                        tr("Audio Media Generator:")
                    };
                    ui.label(RichText::new(which).strong());
                    ui.label(&plugin);
                    ui.with_layout(egui::Layout::right_to_left(egui::Align::Center), |ui| {
                        ui.spacing_mut().item_spacing.x = 2.0;
                        for n in (1..=3u8).rev() {
                            let on = app.settings.fx_columns.clamp(1, 3) == n;
                            if crate::fx_window::columns_button(ui, n, on, is_plugin).clicked() {
                                app.settings.fx_columns = n;
                            }
                        }
                    });
                });
                ui.separator();
                // The frame's size and the media's duration; the help,
                // Replace Plug-In, Match Event Length and Media Properties
                // on the right.
                ui.horizontal(|ui| {
                    use crate::ofx_controls::field;
                    let id =
                        |name: &str| egui::Id::new(("generated-media-field", name.to_string()));
                    if let Some(v) = video {
                        ui.label(tr("Frame Size:"));
                        // Even sizes, 16 to 8192 pixels.
                        let typed = |t: String| {
                            t.trim().parse::<u32>().ok().map(|n| n.clamp(16, 8192) & !1)
                        };
                        let w = field(ui, id("width"), &v.width.to_string(), 52.0, tr("Width"))
                            .and_then(typed);
                        ui.label("x");
                        let h = field(ui, id("height"), &v.height.to_string(), 52.0, tr("Height"))
                            .and_then(typed);
                        if w.is_some() || h.is_some() {
                            size = Some((w.unwrap_or(v.width), h.unwrap_or(v.height)));
                        }
                        ui.add_space(10.0);
                    }
                    ui.label(tr("Duration:"));
                    let shown = self.length.clone();
                    if let Some(t) = field(ui, id("duration"), &shown, 84.0, tr("Duration:")) {
                        length = timecode::parse(&t, rate).filter(|d| *d > Tick::ZERO);
                        self.length = match length {
                            Some(d) => timecode::format(d, rate),
                            None => timecode::format(own_length(&info, duration), rate),
                        };
                    }
                    ui.with_layout(egui::Layout::right_to_left(egui::Align::Center), |ui| {
                        ui.spacing_mut().item_spacing.x = 2.0;
                        if icon_button_ex(ui, Icon::Settings, tr("Media Properties"), false, true)
                            .clicked()
                        {
                            properties = true;
                        }
                        if icon_button_ex(
                            ui,
                            Icon::FitLength,
                            tr("Match Event Length"),
                            false,
                            true,
                        )
                        .clicked()
                        {
                            match_length = true;
                        }
                        let replace = icon_button_ex(
                            ui,
                            Icon::FxAdd,
                            tr("Replace Plug-In"),
                            false,
                            !replacements.is_empty(),
                        );
                        egui::Popup::menu(&replace).show(|ui| {
                            for (name, g) in &replacements {
                                if crate::menus::item(ui, name) {
                                    replacing = Some(g.clone());
                                }
                            }
                        });
                        if let Some(info) = &help {
                            let r = icon_button_ex(ui, Icon::Help, tr("Plug-In Help"), false, true);
                            egui::Popup::menu(&r).width(320.0).show(|ui| {
                                ui.label(RichText::new(&plugin).strong());
                                ui.label(tr(&info.description));
                            });
                        }
                    });
                });
                // The preset, saved and deleted here.
                ui.horizontal(|ui| {
                    ui.label(tr("Preset:"));
                    ui.spacing_mut().item_spacing.x = 2.0;
                    ui.with_layout(egui::Layout::right_to_left(egui::Align::Center), |ui| {
                        if icon_button_ex(ui, Icon::Delete, tr("Delete Preset"), false, user_preset)
                            .clicked()
                        {
                            delete = true;
                        }
                        let named = !self.preset.trim().is_empty();
                        if icon_button_ex(ui, Icon::Save, tr("Save Preset"), false, named).clicked()
                        {
                            save = true;
                        }
                        ui.add_space(4.0);
                        let list = list_button(ui);
                        egui::Popup::menu(&list).show(|ui| {
                            for (name, g) in &presets {
                                if crate::menus::check_item(ui, name, *g == generator, true, "") {
                                    chosen = Some(g.clone());
                                    self.preset = name.clone();
                                }
                            }
                        });
                        ui.add(
                            egui::TextEdit::singleline(&mut self.preset)
                                .desired_width(ui.available_width())
                                .hint_text(tr("(Custom)")),
                        );
                    });
                });
                ui.add_space(4.0);
                let top = ui.min_rect().width();
                match &generator {
                    // An OFX generator's settings, as it describes them.
                    Generator::Plugin(fx) => {
                        let key = crate::ofx::EditorKey {
                            owner: crate::ofx::EditorOwner::Generator(media),
                            index: 0,
                            id: fx.id.clone(),
                        };
                        let columns = usize::from(app.settings.fx_columns.clamp(1, 3));
                        if let Some(place) = place
                            && let Some(new) =
                                crate::ofx::params(ui, &mut app.ofx, key, fx, &place, columns)
                        {
                            chosen = Some(Generator::Plugin(Box::new(new)));
                        }
                    }
                    _ => {
                        egui::Grid::new("generated-media-settings")
                            .num_columns(2)
                            .spacing([10.0, 6.0])
                            .show(ui, |ui| {
                                self.settings_ui(ui, &generator, &mut chosen);
                            });
                    }
                }
                measured = Some(ui.min_rect().width().max(top));
            });
        // The window as wide as its settings (VEGAS's least at least).
        if let Some(w) = measured
            && (w - self.width).abs() > 1.0
        {
            self.width = w.max(LEAST_WIDTH);
            ctx.request_repaint();
        }
        // A color being chosen.
        if let Some((which, picker)) = &mut self.picking {
            match picker.show(ctx) {
                Outcome::Open => {}
                Outcome::Cancelled => self.picking = None,
                Outcome::Chosen(c) => {
                    chosen = Some(with_color(&generator, *which, from_bytes(c)));
                    self.picking = None;
                }
            }
        }
        let field = |name: &str| egui::Id::new(("generated-media", media.0, name.to_string()));
        if properties {
            app.dialogs.media_properties =
                crate::media_properties::MediaPropertiesDialog::new(app, media);
        }
        // Another generator: its preset's name in the box.
        if let Some(g) = replacing.filter(|g| *g != generator) {
            let (_, _, presets) = crate::tabs::generators::plugin_of(app, &g);
            self.preset = presets
                .into_iter()
                .find(|(_, p)| *p == g)
                .map(|(n, _)| n)
                .unwrap_or_default();
            app.modify(|p| set_generator(p, media, g));
        }
        if let Some(g) = chosen.filter(|g| *g != generator) {
            app.modify_merged(field("generator"), |p| set_generator(p, media, g));
        }
        if let Some((w, h)) = size {
            app.modify_merged(field("size"), |p| {
                if let Some(v) = p
                    .media
                    .iter_mut()
                    .find(|m| m.id == media)
                    .and_then(|m| m.video.as_mut())
                {
                    v.width = w;
                    v.height = h;
                }
            });
        }
        // The generated media's own duration: typed, or its event's.
        if match_length {
            length = Some(duration);
        }
        if let Some(d) = length {
            app.modify_merged(field("duration"), |p| {
                if let Some(m) = p.media.iter_mut().find(|m| m.id == media) {
                    m.duration = d;
                }
            });
            self.length = timecode::format(d, rate);
        }
        // Transfer Text Properties: the plug-in's button asked.
        if let Some(t) = app.ofx.take_transfer()
            && t.owner == crate::ofx::EditorOwner::Generator(media)
        {
            let clip = self.clip;
            let n = app.modify(|p| transfer_text_properties(p, clip, &t.fx, &t.keep));
            app.notify(trn!(
                n,
                "{} Titles & Text event took this look.",
                "{} Titles & Text events took this look.",
                n
            ));
        }
        let name = self.preset.trim().to_string();
        if save && !name.is_empty() {
            let presets = &mut app.settings.generator_presets;
            presets.retain(|s| !(s.plugin == key && s.name == name));
            let generator = app
                .project()
                .media(media)
                .and_then(|m| match &m.source {
                    MediaSource::Generated(g) => Some(g.clone()),
                    MediaSource::File { .. } => None,
                })
                .unwrap_or(generator);
            app.settings.generator_presets.push(GeneratorPreset {
                plugin: key.clone(),
                name: name.clone(),
                generator,
            });
            let _ = app.settings.save();
            app.notify(trf!("Preset \"{}\" saved.", name));
        }
        if delete {
            app.settings
                .generator_presets
                .retain(|s| !(s.plugin == key && s.name == name));
            let _ = app.settings.save();
            self.preset.clear();
        }
        open
    }

    /// The plug-in's own settings.
    fn settings_ui(&mut self, ui: &mut egui::Ui, g: &Generator, chosen: &mut Option<Generator>) {
        let mut swatch = |ui: &mut egui::Ui, label: &str, which: usize, rgba: [f32; 4]| {
            ui.label(label);
            if crate::preferences::swatch(ui, to_bytes(rgba), label).clicked() {
                let title = label.trim_end_matches(':');
                self.picking = Some((which, ColorPicker::new(title, to_bytes(rgba))));
            }
            ui.end_row();
        };
        match g {
            // An adjustment event's settings are its effects.
            Generator::Adjustment => {}
            Generator::SolidColor { rgba } => swatch(ui, tr("Color:"), 0, *rgba),
            Generator::Gradient {
                from,
                to,
                angle_deg,
            } => {
                swatch(ui, tr("From:"), 0, *from);
                swatch(ui, tr("To:"), 1, *to);
                ui.label(tr("Angle:"));
                let mut a = *angle_deg;
                if ui
                    .add(
                        egui::DragValue::new(&mut a)
                            .range(-360.0..=360.0)
                            .suffix("°"),
                    )
                    .changed()
                {
                    *chosen = Some(Generator::Gradient {
                        from: *from,
                        to: *to,
                        angle_deg: a,
                    });
                }
                ui.end_row();
            }
            Generator::ColorBars => {
                ui.label(tr("Test pattern type:"));
                ui.label("SMPTE 75%");
                ui.end_row();
            }
            Generator::Checkerboard { size } => {
                ui.label(tr("Square size:"));
                let mut s = *size;
                if ui
                    .add(egui::DragValue::new(&mut s).range(2..=2048).suffix(" px"))
                    .changed()
                {
                    *chosen = Some(Generator::Checkerboard { size: s });
                }
                ui.end_row();
            }
            Generator::Noise { amount, color } => {
                ui.label(tr("Amount:"));
                let mut a = *amount;
                if ui.add(egui::Slider::new(&mut a, 0.0..=1.0)).changed() {
                    *chosen = Some(Generator::Noise {
                        amount: a,
                        color: *color,
                    });
                }
                ui.end_row();
                ui.label("");
                let mut c = *color;
                if crate::widgets::checkbox(ui, &mut c, tr("In color")).changed() {
                    *chosen = Some(Generator::Noise {
                        amount: *amount,
                        color: c,
                    });
                }
                ui.end_row();
            }
            // Drawn apart (`crate::ofx::params`).
            Generator::Plugin(_) => {}
            Generator::TestTone {
                frequency_hz,
                level_db,
            } => {
                ui.label(tr("Frequency:"));
                let mut f = *frequency_hz;
                if ui
                    .add(
                        egui::DragValue::new(&mut f)
                            .range(20.0..=20_000.0)
                            .suffix(" Hz"),
                    )
                    .changed()
                {
                    *chosen = Some(Generator::TestTone {
                        frequency_hz: f,
                        level_db: *level_db,
                    });
                }
                ui.end_row();
                ui.label(tr("Level:"));
                let mut l = *level_db;
                if ui
                    .add(
                        egui::DragValue::new(&mut l)
                            .range(-96.0..=0.0)
                            .suffix(" dBFS"),
                    )
                    .changed()
                {
                    *chosen = Some(Generator::TestTone {
                        frequency_hz: *frequency_hz,
                        level_db: l,
                    });
                }
                ui.end_row();
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn colors_go_where_they_belong() {
        let g = Generator::Gradient {
            from: [1.0, 0.0, 0.0, 1.0],
            to: [0.0, 0.0, 1.0, 1.0],
            angle_deg: 45.0,
        };
        let green = [0.0, 1.0, 0.0, 1.0];
        assert_eq!(
            with_color(&g, 1, green),
            Generator::Gradient {
                from: [1.0, 0.0, 0.0, 1.0],
                to: green,
                angle_deg: 45.0,
            }
        );
        assert_eq!(from_bytes(to_bytes(green)), green);
    }

    #[test]
    fn a_new_generator_renames_media_named_after_the_old_one() {
        let mut p = Project::default();
        let tone = Generator::TestTone {
            frequency_hz: 1000.0,
            level_db: -18.0,
        };
        let id = p.add_media(bv_timeline::MediaInfo::generated(tone, &p.settings));
        let a = Generator::TestTone {
            frequency_hz: 440.0,
            level_db: -18.0,
        };
        set_generator(&mut p, id, a.clone());
        assert_eq!(p.media(id).unwrap().name, a.display_name());
        // A name of the user's own stays.
        p.media.iter_mut().for_each(|m| m.name = "Reference".into());
        set_generator(&mut p, id, Generator::ColorBars);
        assert_eq!(p.media(id).unwrap().name, "Reference");
    }
}
