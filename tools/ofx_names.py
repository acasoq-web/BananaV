"""Writes crates/ofx-sys/src/names.rs from the OpenFX headers in vendor/openfx.

Every `#define kOfx...` of the headers that holds a string becomes a `&CStr`
constant with the header's own name, and every one that holds a whole number
an `i32`, so code can be compared with the specification name for name.

Run from the repository's root: `python tools/ofx_names.py`.
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
INCLUDE = ROOT / "vendor" / "openfx" / "include"
OUT = ROOT / "crates" / "ofx-sys" / "src" / "names.rs"

# The colour configuration's names and the key symbols are not needed.
SKIP = {"ofx-native-v1.5_aces-v1.3_ocio-v2.3.h", "ofxKeySyms.h"}

STRING = re.compile(r'^\s*#\s*define\s+(kOfx\w+)\s+"([^"]*)"\s*(?://.*|/\*.*)?$')
NUMBER = re.compile(r"^\s*#\s*define\s+(kOfx\w+)\s+\(?\s*(?:\(\s*int\s*\)\s*)?(-?\d+)\s*\)?\s*(?://.*|/\*.*)?$")
# Another name's alias, or the limits of an int.
ALIAS = re.compile(r"^\s*#\s*define\s+(kOfx\w+)\s+(kOfx\w+|INT_MAX|INT_MIN)\s*(?://.*|/\*.*)?$")
LIMITS = {"INT_MAX": "i32::MAX", "INT_MIN": "i32::MIN"}


def main():
    names = {}
    order = []
    for header in sorted(INCLUDE.glob("*.h")):
        if header.name in SKIP:
            continue
        for line in header.read_text(encoding="utf-8", errors="replace").splitlines():
            m = STRING.match(line)
            kind = "str"
            if not m:
                m = NUMBER.match(line)
                kind = "int"
            if not m:
                m = ALIAS.match(line)
                kind = "alias"
            if not m:
                continue
            name, value = m.group(1), m.group(2)
            if name in names:
                if names[name] != (kind, value):
                    raise SystemExit(f"{name} defined twice with different values")
                continue
            names[name] = (kind, value)
            order.append((header.name, name))

    lines = [
        "//! Every name of the OpenFX headers (`vendor/openfx/include`), spelled",
        "//! as the specification spells it. Generated by `tools/ofx_names.py`:",
        "//! do not edit by hand.",
        "",
        "#![allow(non_upper_case_globals)]",
        "",
        "use std::ffi::CStr;",
        "",
    ]
    current = None
    for header, name in order:
        if header != current:
            if current is not None:
                lines.append("")
            lines.append(f"// {header}")
            current = header
        kind, value = names[name]
        if kind == "str":
            lines.append(f'pub const {name}: &CStr = c"{value}";')
        elif kind == "int":
            lines.append(f"pub const {name}: i32 = {value};")
        elif value in LIMITS:
            lines.append(f"pub const {name}: i32 = {LIMITS[value]};")
        else:
            target = names.get(value)
            if target is None:
                raise SystemExit(f"{name} aliases the unknown {value}")
            ty = "&CStr" if target[0] == "str" else "i32"
            lines.append(f"pub const {name}: {ty} = {value};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(order)} names written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
